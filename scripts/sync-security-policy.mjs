import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const policy = JSON.parse(fs.readFileSync(path.join(root,'config/security-policy.json'),'utf8'))
for (const [name,values] of Object.entries(policy)) {
  if (!/^[a-z-]+$/.test(name) || !Array.isArray(values) || !values.length || values.some(v => typeof v !== 'string' || /[;"\r\n]/.test(v))) throw new Error('invalid CSP directive')
}
if (JSON.stringify(policy['script-src']) !== JSON.stringify(["'self'"]) || JSON.stringify(policy['style-src']) !== JSON.stringify(["'self'"])) throw new Error('executable CSP origins must remain self only')
const header = Object.entries(policy).map(([name,values]) => `${name} ${values.join(' ')}`).join('; ')
const caddyFile = path.join(root,'deploy/caddy/Caddyfile')
const caddy = fs.readFileSync(caddyFile,'utf8')
const marker = /\t\t# BEGIN GENERATED CSP\n[\s\S]*?\t\t# END GENERATED CSP/g
if ([...caddy.matchAll(marker)].length !== 1) throw new Error('expected one Caddy CSP marker')
const outputs = new Map([
  [path.join(root,'edge/src/security-policy.ts'), `// Generated by scripts/sync-security-policy.mjs; edit config/security-policy.json.\nexport const CONTENT_SECURITY_POLICY = ${JSON.stringify(header)}\n`],
  [caddyFile,caddy.replace(marker, () => `\t\t# BEGIN GENERATED CSP\n\t\tContent-Security-Policy "${header}"\n\t\t# END GENERATED CSP`)],
])
for (const [file,content] of outputs) {
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(file) || fs.readFileSync(file,'utf8') !== content) {console.error(`generated CSP drift: ${path.relative(root,file)}`);process.exitCode=1}
  } else fs.writeFileSync(file,content)
}
